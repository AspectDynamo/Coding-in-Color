/**
 * Generates supabase/seed.sql from the deterministic synthetic demo dataset
 * (src/backend/demo). Run via `npm run db:seed` or `npx tsx scripts/generate-seed.ts`.
 *
 *   --out=<path>      output file (default supabase/seed.sql)
 *   --anchor=<date>   demo "today" (default 2026-11-15)
 *
 * Credential rows: the demo access codes are hashed exactly like the Worker does —
 *   hex HMAC-SHA256(key = CREDENTIAL_PEPPER as UTF-8, message = normalized code)
 * where normalized = uppercase, strip spaces/dashes, I/L -> 1, O -> 0 (U dropped; demo codes
 * contain none of these). CREDENTIAL_PEPPER comes from the environment or `.dev.vars`. If it is
 * missing, credential rows are omitted (and a warning printed): no raw codes are ever written.
 */
import { createHmac } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_DEMO_ANCHOR, generateDemoDataset } from '../src/backend/demo/generate';
import { demoUuid } from '../src/backend/demo/prng';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function arg(name: string): string | undefined {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : undefined;
}

function readVars(file: string): Record<string, string> {
  const out: Record<string, string> = {};
  if (!existsSync(file)) return out;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (!m || line.trimStart().startsWith('#')) continue;
    let v = m[2] as string;
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'")))
      v = v.slice(1, -1);
    out[m[1] as string] = v;
  }
  return out;
}

function normalizeAccessCode(input: string): string {
  return input
    .toUpperCase()
    .replace(/[\s-]+/g, '')
    .replace(/[IL]/g, '1')
    .replace(/O/g, '0')
    .replace(/U/g, '');
}

/* ---------------- SQL literal rendering ---------------- */

function lit(v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`non-finite number in seed: ${v}`);
    return String(v);
  }
  if (typeof v === 'string') return `'${v.replace(/'/g, "''")}'`;
  if (Array.isArray(v)) {
    if (v.length === 0) return `'{}'::text[]`;
    return `array[${v.map((x) => lit(String(x))).join(', ')}]::text[]`;
  }
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  throw new Error(`unsupported seed value type: ${typeof v}`);
}

function insert(table: string, rows: Record<string, unknown>[], batch = 200): string {
  if (rows.length === 0) return `-- ${table}: no rows\n`;
  const cols = Object.keys(rows[0] as Record<string, unknown>);
  const out: string[] = [`-- ${table}: ${rows.length} rows`];
  for (let i = 0; i < rows.length; i += batch) {
    const chunk = rows.slice(i, i + batch);
    const values = chunk.map((r) => {
      const keys = Object.keys(r);
      if (keys.length !== cols.length || keys.some((k, j) => k !== cols[j])) {
        throw new Error(`inconsistent columns in ${table} rows`);
      }
      return `  (${cols.map((c) => lit(r[c])).join(', ')})`;
    });
    out.push(`insert into ${table} (${cols.join(', ')}) values\n${values.join(',\n')};`);
  }
  return out.join('\n') + '\n';
}

/* ---------------- main ---------------- */

const anchor = arg('anchor') ?? DEFAULT_DEMO_ANCHOR;
const outPath = resolve(root, arg('out') ?? 'supabase/seed.sql');
const vars = {
  ...readVars(resolve(root, '.dev.vars')),
  ...(Object.fromEntries(
    Object.entries(process.env).filter(([, v]) => typeof v === 'string' && v !== ''),
  ) as Record<string, string>),
};
const pepper = vars['CREDENTIAL_PEPPER'];
const keyVersion = Number.parseInt(vars['CREDENTIAL_KEY_VERSION'] ?? '1', 10) || 1;

const d = generateDemoDataset(anchor);

const parts: string[] = [];
parts.push(`-- =====================================================================================
-- SYNTHETIC DEMO DATA — NOT REAL STUDENTS.
-- Generated by scripts/generate-seed.ts from src/backend/demo (deterministic; anchor ${anchor}).
-- Every student, staff member, cohort and score below is fictional. Do not edit by hand:
-- re-run \`npm run db:seed\` (or \`npx tsx scripts/generate-seed.ts\`).
-- Access-code hashes use the CREDENTIAL_PEPPER present when this file was generated; no raw
-- codes are stored here. DEMO / DEVELOPMENT DATABASES ONLY.
-- =====================================================================================

begin;

-- Safety: refuse to clobber a database that holds real (non-synthetic) people.
do $$
begin
  if exists (select 1 from students where not is_synthetic)
     or exists (select 1 from staff_users where not is_synthetic) then
    raise exception 'seed.sql refused: non-synthetic students or staff exist in this database';
  end if;
end;
$$;

-- Replace any previous synthetic data (TRUNCATE does not fire the audit_log append-only trigger).
truncate table
  audit_log, ai_reports, project_evaluations, attempt_skill_scores, assessment_responses,
  assessment_attempts, assessment_sessions, question_answer_keys, questions, assessments,
  guardian_contacts, consent_records, student_credentials, cohort_students, students,
  cohorts, staff_program_assignments, staff_users, courses, programs
  cascade;
`);

parts.push(insert('programs', d.programs as unknown as Record<string, unknown>[]));
parts.push(insert('courses', d.courses as unknown as Record<string, unknown>[]));
parts.push(insert('staff_users', d.staff as unknown as Record<string, unknown>[]));
parts.push(
  insert('staff_program_assignments', d.staffAssignments as unknown as Record<string, unknown>[]),
);
parts.push(insert('cohorts', d.cohorts as unknown as Record<string, unknown>[]));
parts.push(insert('students', d.students as unknown as Record<string, unknown>[]));

if (pepper) {
  const studentById = new Map(d.students.map((s) => [s.id, s]));
  const creds = d.demoCredentials.map((c) => {
    const student = studentById.get(c.studentId);
    if (!student) throw new Error('demo credential for unknown student');
    return {
      id: demoUuid('credential', c.studentId),
      student_id: c.studentId,
      credential_hash: createHmac('sha256', pepper)
        .update(normalizeAccessCode(c.code), 'utf8')
        .digest('hex'),
      key_version: keyVersion,
      created_by: null,
      created_at: student.created_at,
      revoked_at: null,
      revoked_reason: null,
      last_used_at: null,
    };
  });
  parts.push(insert('student_credentials', creds));
} else {
  parts.push(
    '-- student_credentials: OMITTED (CREDENTIAL_PEPPER not set when this file was generated)\n',
  );
  console.warn(
    '[generate-seed] WARNING: CREDENTIAL_PEPPER is not set (env or .dev.vars). Credential rows were omitted: ' +
      'students exist but no demo access codes will work. Run `npm run setup` and regenerate.',
  );
}

parts.push(insert('cohort_students', d.cohortStudents as unknown as Record<string, unknown>[]));
parts.push(insert('consent_records', d.consentRecords as unknown as Record<string, unknown>[]));
parts.push(insert('guardian_contacts', d.guardianContacts as unknown as Record<string, unknown>[]));
parts.push(insert('assessments', d.assessments as unknown as Record<string, unknown>[]));
parts.push(insert('questions', d.questions as unknown as Record<string, unknown>[]));
parts.push(insert('question_answer_keys', d.answerKeys as unknown as Record<string, unknown>[]));
parts.push(insert('assessment_sessions', d.sessions as unknown as Record<string, unknown>[]));
parts.push(insert('assessment_attempts', d.attempts as unknown as Record<string, unknown>[]));
parts.push(
  insert('assessment_responses', d.responses as unknown as Record<string, unknown>[], 400),
);
parts.push(
  insert('attempt_skill_scores', d.skillScores as unknown as Record<string, unknown>[], 400),
);
parts.push(insert('audit_log', d.auditLog as unknown as Record<string, unknown>[]));
parts.push('commit;\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, parts.join('\n'), 'utf8');
console.log(
  `[generate-seed] wrote ${outPath} (${d.students.length} students, ${d.attempts.length} attempts, ` +
    `${d.responses.length} responses; credentials: ${pepper ? `${d.demoCredentials.length} (key_version ${keyVersion})` : 'omitted'})`,
);
